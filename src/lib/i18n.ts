export function getLang(): LangCode {
  if (typeof window === 'undefined') return 'ko';
  return (localStorage.getItem('bingo_lang') as LangCode) || 'ko';
}

export function setLang(lang: LangCode) {
  localStorage.setItem('bingo_lang', lang);
}
